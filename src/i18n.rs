impl Tr {
    pub fn load_error(&self, e: &LoadError) -> String {
        match e {
            LoadError::Open(d) => fill(self.err_open, &[d]),
            LoadError::Damaged(d) => fill(self.err_damaged, &[d]),
            LoadError::NoContainer => self.err_no_container.into(),
            LoadError::NoOpf => self.err_no_opf.into(),
            LoadError::NoText => self.err_no_text.into(),
            LoadError::NotWord => self.err_not_word.into(),
            LoadError::Password => self.err_password.into(),
            LoadError::Pdf(d) => fill(self.err_pdf, &[d]),
            LoadError::NoPages => self.err_no_pages.into(),
            LoadError::NoPdfium(d) => fill(self.err_no_pdfium, &[d]),
        }
    }
}

